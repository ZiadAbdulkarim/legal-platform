  static isInitialized = false;

  /**
   * Initializes data from JSON or embedded fallback for offline resilience.
   */
  static async init() {
    if (this.isInitialized) return;

    try {
      const [catRes, topRes] = await Promise.all([
        fetch('./src/data/categories.json').then(r => r.json()).catch(() => null),
        fetch('./src/data/topics.json').then(r => r.json()).catch(() => null)
      ]);

      if (catRes && topRes) {
        this.categories = catRes.categories || [];
        this.circularInfo = catRes.circular_info || null;
        this.topics = topRes.topics || [];
        this.importantNotes = topRes.important_judicial_notes || [];
        this.isInitialized = true;
        return;
      }
    } catch (e) {
      console.warn('Could not fetch JSON directly, falling back to embedded dataset:', e);
    }

    // Direct Embedded Dataset (Exact mirror of data/categories.json and data/topics.json)
    this.initFallbackData();
    this.isInitialized = true;
  }

  static getCategories() {
    return this.categories;
  }

  static getTopics() {
    return this.topics;
  }

  static getImportantNotes() {
    return this.importantNotes;
  }

  static getCircularInfo() {
    return this.circularInfo;
  }

  static getTopicById(id) {
    return this.topics.find(t => t.id === id);
  }

  /**
   * Performs high-speed Arabic full-text search across titles, legal articles, and charge descriptions.
   */
  static searchTopics({ query = '', categoryId = 'all', onlyFavorites = false, favoriteIds = [] } = {}) {
    const cleanQuery = query.trim().toLowerCase();

    return this.topics.filter(topic => {
      // Category filter
      if (categoryId && categoryId !== 'all' && topic.category_id !== categoryId) {
        return false;
      }

      // Favorites filter
      if (onlyFavorites && !favoriteIds.includes(topic.id)) {
        return false;
      }

      // Query filter
      if (!cleanQuery) return true;

      const titleMatch = topic.title.toLowerCase().includes(cleanQuery);
      const formulaMatch = topic.referral_formula.toLowerCase().includes(cleanQuery);
      const descMatch = topic.full_charge_description.toLowerCase().includes(cleanQuery);
      const keywordMatch = topic.keywords && topic.keywords.some(kw => kw.toLowerCase().includes(cleanQuery));
      const articleMatch = topic.legal_articles && topic.legal_articles.some(a => 
        a.article.toLowerCase().includes(cleanQuery) || 
        a.law.toLowerCase().includes(cleanQuery) ||
        a.summary.toLowerCase().includes(cleanQuery)
      );

      return titleMatch || formulaMatch || descMatch || keywordMatch || articleMatch;
    });
  }

